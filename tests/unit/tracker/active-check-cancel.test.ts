/**
 * Active-check stop/cancel path regression tests.
 *
 * Verifies the four stop/cancel paths for the active-check workflow:
 *   1. Cancel queued item  — /api/cancel-queued
 *   2. Cancel running item — /api/cancel-running
 *   3. Force stop task     — /api/task/force-stop
 *   4. Stop all daemons   — uses workflowNameFromInstance("Active Check N")
 *
 * active-check uses batch.mode="shared-context-pool" (poolSize: 4). These
 * tests verify the SQLite-backed cancel/stop handlers correctly handle
 * active-check tasks — the workflow name is the only thing distinguishing
 * active-check from separations in the control-DB layer.
 *
 * Tests A–D from the Phase-A / Task-4b audit plan:
 *   A: workflowNameFromInstance returns "active-check" for active-check instances
 *   B: daemon-stop filtering correctly distinguishes active-check instances
 *   C: cancel_task command is written for an active-check task
 *   D: cancellation of queued active-check task writes BOTH tracker row AND JSONL log line
 */
